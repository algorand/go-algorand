func opPoseidon2(cx *EvalContext) error {
	config := Poseidon2Config(cx.program[cx.pc+1])
	fs, ok := poseidon2ConfigSpecByField(config)
	if !ok { // no version check yet, all configs appeared at once
		return fmt.Errorf("invalid poseidon2 config %s", config)
	}

	last := len(cx.Stack) - 1
	data := cx.Stack[last].Bytes
	if len(data) == 0 {
		return fmt.Errorf("the input data cannot be empty")
	}
	if len(data)%32 != 0 {
		return fmt.Errorf("the input data must be a multiple of 32 bytes")
	}

	var poseidon hash.Hash

	switch fs.field {
	case BLS12_381t2:
		poseidon = bls12_381poseidon2.NewMerkleDamgardHasher()
	case BN254t2:
		poseidon = bn254poseidon2.NewMerkleDamgardHasher()
	default:
		return fmt.Errorf("invalid poseidon2 group %s", config)
	}

	// unlike most hash.Hash objects, a poseidon hasher has strict requirements,
	// therefore Write() can return an error. The input must be a multiple of
	// the curve's encoded element size, and no element may exceed the curve
	// modulus.
	if _, err := poseidon.Write(cx.Stack[last].Bytes); err != nil {
		return fmt.Errorf("invalid poseidon2 input %w", err)
	}

	cx.Stack[last].Bytes = poseidon.Sum(nil)
	return nil
}

