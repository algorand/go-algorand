// falconVerify implements falcon_verify for a single Falcon configuration. The
// original opcode had no immediate and could only mean Falcon-1024, so it
// supplies that config itself, while the immediate form reads it from the
// program.
func falconVerify(cx *EvalContext, config FalconConfig) error {
	last := len(cx.Stack) - 1 // index of PK
	prev := last - 1          // index of signature
	pprev := prev - 1         // index of data

	fs, ok := falconConfigSpecByField(config)
	if !ok { // no version check yet, both configs appeared at once
		return fmt.Errorf("invalid falcon config %s", config)
	}

	pk := cx.Stack[last].Bytes
	if len(pk) != fs.pubKeyLen {
		return fmt.Errorf("invalid public key size %d != %d", len(pk), fs.pubKeyLen)
	}

	var err error
	switch config {
	case FalconDet1024:
		var fv crypto.Falcon1024Verifier
		copy(fv.PublicKey[:], pk)
		err = fv.VerifyBytes(cx.Stack[pprev].Bytes, crypto.Falcon1024Signature(cx.Stack[prev].Bytes))
	case FalconDet512:
		var fv crypto.Falcon512Verifier
		copy(fv.PublicKey[:], pk)
		err = fv.VerifyBytes(cx.Stack[pprev].Bytes, crypto.Falcon512Signature(cx.Stack[prev].Bytes))
	default:
		return fmt.Errorf("invalid falcon config %s", config)
	}

	cx.Stack[pprev] = boolToSV(err == nil)
	cx.Stack = cx.Stack[:prev]
	return nil
}

func opFalcon1024Verify(cx *EvalContext) error {
	return falconVerify(cx, FalconDet1024)
}

func opFalconVerify(cx *EvalContext) error {
	return falconVerify(cx, FalconConfig(cx.program[cx.pc+1]))
}

type pqSchemeCost struct {
	scheme protocol.PQScheme
	cost   int
}

// verifyTxnSigCosts are the base costs of verify_txn_sig for each PQSig scheme,
// matching the costs of the standalone opcodes that verify the same schemes.
// Every scheme in crypto.LookupPQScheme must appear here.
var verifyTxnSigCosts = []pqSchemeCost{
	{protocol.PQSchemeEd25519, 1900},    // ed25519verify
	{protocol.PQSchemeFalcon1024, 1700}, // falcon_verify FalconDet1024
	{protocol.PQSchemeFalcon512, 850},   // falcon_verify FalconDet512
}

// Every scheme hashes the whole signed message, and deriving the address from
// the envelope hashes the whole public key, so verify_txn_sig also charges
// verifyTxnSigChunkCost per verifyTxnSigChunkSize bytes of the transaction's
// bytes to sign and of the public key. Benchmarks put the marginal hashing cost
// of every scheme at about 40ns per 32 bytes.
const verifyTxnSigChunkCost = 4
const verifyTxnSigChunkSize = 32

// verifyTxnSigArgs decodes and validates verify_txn_sig's arguments, the PQSig
// envelope and address at the top of stack. An envelope that is malformed, or
// names an unknown or disabled scheme, is a malformed argument, not merely a
// signature that fails to verify.
func verifyTxnSigArgs(cx *EvalContext, stack []stackValue) (transactions.PQSig, basics.Address, error) {
	last := len(stack) - 1 // index of address
	prev := last - 1       // index of signature

	var pqsig transactions.PQSig
	var addr basics.Address
	if len(stack[last].Bytes) != len(addr) {
		return pqsig, addr, fmt.Errorf("invalid address size %d != %d", len(stack[last].Bytes), len(addr))
	}
	copy(addr[:], stack[last].Bytes)

	rem, err := pqsig.UnmarshalMsg(stack[prev].Bytes)
	if err != nil {
		return pqsig, addr, fmt.Errorf("invalid pqsig: %w", err)
	}
	if len(rem) != 0 {
		return pqsig, addr, fmt.Errorf("invalid pqsig: %d trailing bytes", len(rem))
	}
	if err := pqsig.ValidateScheme(*cx.Proto); err != nil {
		return pqsig, addr, fmt.Errorf("invalid pqsig: %w", err)
	}
	return pqsig, addr, nil
}

// unpricedVerifyTxnSigCost is charged for a valid scheme missing from
// verifyTxnSigCosts, which the op would go on to verify. It exceeds any budget,
// so such an omission fails rather than undercharging a heavier scheme.
// TestVerifyTxnSigCostsCoverSchemes ensures it is never charged.
const unpricedVerifyTxnSigCost = math.MaxInt

// verifyTxnSigCost charges verify_txn_sig by the scheme named in its PQSig
// envelope, plus the length of the transaction's bytes to sign and of the
// envelope's public key. Invalid arguments cost 1, because opVerifyTxnSig
// rejects exactly the same arguments, so the program fails immediately.
func verifyTxnSigCost(cx *EvalContext, stack []stackValue) int {
	pqsig, _, err := verifyTxnSigArgs(cx, stack)
	if err != nil {
		return 1
	}
	i := slices.IndexFunc(verifyTxnSigCosts, func(c pqSchemeCost) bool { return c.scheme == pqsig.Scheme })
	if i < 0 {
		return unpricedVerifyTxnSigCost
	}
	hashed := len(protocol.Transaction) + len(protocol.Encode(&cx.txn.Txn)) + len(pqsig.PublicKey)
	return verifyTxnSigCosts[i].cost + verifyTxnSigChunkCost*basics.DivCeil(hashed, verifyTxnSigChunkSize)
}

func verifyTxnSigCostDoc() string {
	costs := make([]string, len(verifyTxnSigCosts))
	for i, c := range verifyTxnSigCosts {
		costs[i] = fmt.Sprintf("%s=%d", c.scheme, c.cost)
	}
	return fmt.Sprintf("%s; plus %d per %d bytes of the transaction's bytes to sign and the public key",
		strings.Join(costs, "; "), verifyTxnSigChunkCost, verifyTxnSigChunkSize)
}

// opVerifyTxnSig verifies a PQSig envelope over the current transaction, as it
// would be signed for submission (crypto.HashRep, "TX" || msgpack(txn)), by
// the address on top of the stack. The signed bytes are computed internally
// and never placed on the stack.
func opVerifyTxnSig(cx *EvalContext) error {
	last := len(cx.Stack) - 1 // index of address
	prev := last - 1          // index of signature

	pqsig, addr, err := verifyTxnSigArgs(cx, cx.Stack)
	if err != nil {
		return err
	}
	cx.Stack[prev] = boolToSV(pqsig.Verify(*cx.Proto, cx.txn.Txn, addr) == nil)
	cx.Stack = cx.Stack[:last]
	return nil
}

// Msg is data meant to be signed and then verified with the
// ed25519verify opcode.
type Msg struct {
	_struct     struct{}      `codec:",omitempty,omitemptyarray"`
	ProgramHash crypto.Digest `codec:"p"`
	Data        []byte        `codec:"d"`
}

// ToBeHashed implements crypto.Hashable
func (msg Msg) ToBeHashed() (protocol.HashID, []byte) {
	return protocol.ProgramData, append(msg.ProgramHash[:], msg.Data...)
}

// programHash lets us lazily compute H(cx.program)
func (cx *EvalContext) programHash() crypto.Digest {
	if cx.programHashCached == (crypto.Digest{}) {
		cx.programHashCached = crypto.HashObj(Program(cx.program))
	}
	return cx.programHashCached
}

func opEd25519Verify(cx *EvalContext) error {
	last := len(cx.Stack) - 1 // index of PK
	prev := last - 1          // index of signature
	pprev := prev - 1         // index of data

	var sv crypto.SignatureVerifier
	if len(cx.Stack[last].Bytes) != len(sv) {
		return errors.New("invalid public key")
	}
	copy(sv[:], cx.Stack[last].Bytes)

	var sig crypto.Signature
	if len(cx.Stack[prev].Bytes) != len(sig) {
		return errors.New("invalid signature")
	}
	copy(sig[:], cx.Stack[prev].Bytes)

	msg := Msg{ProgramHash: cx.programHash(), Data: cx.Stack[pprev].Bytes}
	cx.Stack[pprev] = boolToSV(sv.Verify(msg, sig))
	cx.Stack = cx.Stack[:prev]
	return nil
}

func opEd25519VerifyBare(cx *EvalContext) error {
	last := len(cx.Stack) - 1 // index of PK
	prev := last - 1          // index of signature
	pprev := prev - 1         // index of data

	var sv crypto.SignatureVerifier
	if len(cx.Stack[last].Bytes) != len(sv) {
		return errors.New("invalid public key")
	}
	copy(sv[:], cx.Stack[last].Bytes)

	var sig crypto.Signature
	if len(cx.Stack[prev].Bytes) != len(sig) {
		return errors.New("invalid signature")
	}
	copy(sig[:], cx.Stack[prev].Bytes)

	cx.Stack[pprev] = boolToSV(sv.VerifyBytes(cx.Stack[pprev].Bytes, sig))
	cx.Stack = cx.Stack[:prev]
	return nil
}

func leadingZeros(size int, b *big.Int) ([]byte, error) {
	byteLength := (b.BitLen() + 7) / 8
	if size < byteLength {
		return nil, fmt.Errorf("insufficient buffer size: %d < %d", size, byteLength)
	}
	buf := make([]byte, size)
	b.FillBytes(buf)
	return buf, nil
}

var ecdsaVerifyCosts = []int{
	Secp256k1: 1700,
	Secp256r1: 2500,
}

var secp256r1 = elliptic.P256()

func opEcdsaVerify(cx *EvalContext) error {
	ecdsaCurve := EcdsaCurve(cx.program[cx.pc+1])
	fs, ok := ecdsaCurveSpecByField(ecdsaCurve)
	if !ok || fs.version > cx.version {
		return fmt.Errorf("invalid curve %d", ecdsaCurve)
	}

	if fs.field != Secp256k1 && fs.field != Secp256r1 {
		return fmt.Errorf("unsupported curve %d", fs.field)
	}

	last := len(cx.Stack) - 1 // index of PK y
	prev := last - 1          // index of PK x
	pprev := prev - 1         // index of signature s
	fourth := pprev - 1       // index of signature r
	fifth := fourth - 1       // index of data

	pkY := cx.Stack[last].Bytes
	pkX := cx.Stack[prev].Bytes
	sigS := cx.Stack[pprev].Bytes
	sigR := cx.Stack[fourth].Bytes
	msg := cx.Stack[fifth].Bytes

	if len(msg) != 32 {
		return fmt.Errorf("the signed data must be 32 bytes long, not %d", len(msg))
	}

	x := new(big.Int).SetBytes(pkX)
	y := new(big.Int).SetBytes(pkY)

	var result bool
	if fs.field == Secp256k1 {
		signature := make([]byte, 0, len(sigR)+len(sigS))
		signature = append(signature, sigR...)
		signature = append(signature, sigS...)

		pubkey := secp256k1.S256().Marshal(x, y)
		result = secp256k1.VerifySignature(pubkey, msg, signature)
	} else if fs.field == Secp256r1 {
		if !cx.Proto.EnablePrecheckECDSACurve || secp256r1.IsOnCurve(x, y) {
			pubkey := ecdsa.PublicKey{
				Curve: secp256r1,
				X:     x,
				Y:     y,
			}
			r := new(big.Int).SetBytes(sigR)
			s := new(big.Int).SetBytes(sigS)
			result = ecdsa.Verify(&pubkey, msg, r, s)
		}
	}

	cx.Stack[fifth] = boolToSV(result)
	cx.Stack = cx.Stack[:fourth]
	return nil
}

var ecdsaDecompressCosts = []int{
	Secp256k1: 650,
	Secp256r1: 2400,
}

func opEcdsaPkDecompress(cx *EvalContext) error {
	ecdsaCurve := EcdsaCurve(cx.program[cx.pc+1])
	fs, ok := ecdsaCurveSpecByField(ecdsaCurve)
	if !ok || fs.version > cx.version {
		return fmt.Errorf("invalid curve %d", ecdsaCurve)
	}

	if fs.field != Secp256k1 && fs.field != Secp256r1 {
		return fmt.Errorf("unsupported curve %d", fs.field)
	}

	last := len(cx.Stack) - 1 // compressed PK

	pubkey := cx.Stack[last].Bytes
	var x, y *big.Int
	if fs.field == Secp256k1 {
		x, y = secp256k1.DecompressPubkey(pubkey)
		if x == nil {
			return fmt.Errorf("invalid pubkey")
		}
	} else if fs.field == Secp256r1 {
		x, y = elliptic.UnmarshalCompressed(elliptic.P256(), pubkey)
		if x == nil {
			return fmt.Errorf("invalid compressed pubkey")
		}
	}

	var err error
	cx.Stack[last].Uint = 0
	cx.Stack[last].Bytes, err = leadingZeros(32, x)
	if err != nil {
		return fmt.Errorf("x component zeroing failed: %w", err)
	}

	var sv stackValue
	sv.Bytes, err = leadingZeros(32, y)
	if err != nil {
		return fmt.Errorf("y component zeroing failed: %w", err)
	}

	cx.Stack = append(cx.Stack, sv)
	return nil
}

func opEcdsaPkRecover(cx *EvalContext) error {
	ecdsaCurve := EcdsaCurve(cx.program[cx.pc+1])
	fs, ok := ecdsaCurveSpecByField(ecdsaCurve)
	if !ok || fs.version > cx.version {
		return fmt.Errorf("invalid curve %d", ecdsaCurve)
	}

	if fs.field != Secp256k1 {
		return fmt.Errorf("unsupported curve %d", fs.field)
	}

	last := len(cx.Stack) - 1 // index of signature s
	prev := last - 1          // index of signature r
	pprev := prev - 1         // index of recovery id
	fourth := pprev - 1       // index of data

	sigS := cx.Stack[last].Bytes
	sigR := cx.Stack[prev].Bytes
	recid := cx.Stack[pprev].Uint
	msg := cx.Stack[fourth].Bytes

	if recid > 3 {
		return fmt.Errorf("invalid recovery id: %d", recid)
	}

	signature := make([]byte, 0, len(sigR)+len(sigS)+1)
	signature = append(signature, sigR...)
	signature = append(signature, sigS...)
	signature = append(signature, uint8(recid))

	pk, err := secp256k1.RecoverPubkey(msg, signature)
	if err != nil {
		return fmt.Errorf("pubkey recover failed: %s", err.Error())
	}
	x, y := secp256k1.S256().Unmarshal(pk)
	if x == nil {
		return fmt.Errorf("pubkey unmarshal failed")
	}

	cx.Stack[fourth].Uint = 0
	cx.Stack[fourth].Bytes, err = leadingZeros(32, x)
	if err != nil {
		return fmt.Errorf("x component zeroing failed: %s", err.Error())
	}
	cx.Stack[pprev].Uint = 0
	cx.Stack[pprev].Bytes, err = leadingZeros(32, y)
	if err != nil {
		return fmt.Errorf("y component zeroing failed: %s", err.Error())
	}
	cx.Stack = cx.Stack[:prev]
	return nil
}

type rawMessage []byte

func (rm rawMessage) ToBeHashed() (protocol.HashID, []byte) {
	return "", []byte(rm)
}

func opVrfVerify(cx *EvalContext) error {
	last := len(cx.Stack) - 1 // PK
	prev := last - 1          // proof
	pprev := prev - 1         // data

	data := rawMessage(cx.Stack[pprev].Bytes)
	proofbytes := cx.Stack[prev].Bytes
	var proof crypto.VrfProof
	if len(proofbytes) != len(proof) {
		return fmt.Errorf("vrf proof wrong size %d != %d", len(proofbytes), len(proof))
	}
	copy(proof[:], proofbytes[:])

	pubkeybytes := cx.Stack[last].Bytes
	var pubkey crypto.VrfPubkey
	if len(pubkeybytes) != len(pubkey) {
		return fmt.Errorf("vrf pubkey wrong size %d != %d", len(pubkeybytes), len(pubkey))
	}
	copy(pubkey[:], pubkeybytes[:])

	var verified bool
	var output []byte
	std := VrfStandard(cx.program[cx.pc+1])
	ss, ok := vrfStandardSpecByField(std)
	if !ok || ss.version > cx.version {
		return fmt.Errorf("invalid VRF standard %s", std)
	}
	switch std {
	case VrfAlgorand:
		var out crypto.VrfOutput
		verified, out = pubkey.Verify(proof, data)
		output = out[:]
	default:
		return fmt.Errorf("unsupported vrf_verify standard %s", std)
	}

	cx.Stack[pprev].Bytes = output[:]
	cx.Stack[prev] = boolToSV(verified)
	cx.Stack = cx.Stack[:last] // pop 1 because we take 3 args and return 2
	return nil
}
